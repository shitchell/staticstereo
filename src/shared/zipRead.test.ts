const KEEP = mkdtempSync(join(tmpdir(), 'stst-zipread-'))
afterAll(() => rmSync(KEEP, { recursive: true, force: true }))

const te = new TextEncoder()

/**
 * A deterministic word soup, compressible enough that `/usr/bin/zip` chooses
 * deflate for it. That choice is zip's and not ours, so `methods` is asserted
 * rather than assumed in every test that relies on it.
 *
 * Deliberately not shared with `zip.test.ts`'s generator of the same shape.
 * That one exists to make zlib's *level* visible in the output bytes and is
 * sized for that; this one only has to clear zip's store-vs-deflate threshold.
 * Coupling them would make a change for one test's reason silently alter the
 * other's fixture.
 */
function soup(words: number): Uint8Array {
  const vocab = ['alpha', 'beta', 'gamma', 'delta', 'epsilon', 'zeta', 'eta', 'theta']
  // A plain LCG, not `Math.random`: a fixture that differs per run cannot
  // support a byte-exactness claim.
  let x = 7
  const out: string[] = []
  for (let i = 0; i < words; i++) {
    x = (x * 1103515245 + 12345) >>> 0
    out.push(vocab[(x >>> 16) % vocab.length] as string)
  }
  return te.encode(out.join(' '))
}

const SOUP = soup(1000)

/**
 * A non-ASCII entry name, and the reason it is in the acceptance set: design
 * §6.2 puts baked masks in the container, and mask names derive from
 * `layerName()`, which returns the author's own text. Cyrillic, an em dash and
 * an astral-plane emoji cover two-, three- and four-byte UTF-8 in one name.
 *
 * `/usr/bin/zip` sets general-purpose bit 11 (0x800) on **this** entry and
 * leaves it clear on the ASCII ones, so one archive exercises both of the
 * reader's name-decoding paths. That is asserted, not assumed.
 */
const UNICODE_NAME = 'ref/masks/масло — ☕𝄞.txt'

const MIMETYPE = te.encode('application/x-stst')

/** The declared truth the reader is checked against — not a re-read of disk. */
const TREE: readonly { readonly name: string; readonly data: Uint8Array }[] = [
  { name: 'mimetype', data: MIMETYPE },
  { name: 'ref/soup.txt', data: SOUP },
  { name: 'ref/masks/tiny.bin', data: te.encode('tiny') },
  { name: UNICODE_NAME, data: SOUP },
]

/** `zip -r` records a traversed directory as an entry of its own. */
const TREE_DIRS = ['ref/', 'ref/masks/']

/**
 * Build the tree on disk and hand it to `/usr/bin/zip`, returning the bytes.
 *
 * Memoised per flag set because `zip` is a process spawn, not because the
 * output is stable: it stamps real mtimes, so two runs differ in bytes. No
 * assertion here is on the archive's bytes — only on what comes back out of
 * it — so that is harmless, and it is also the point. A committed blob would
 * freeze one day's `zip` and stop measuring the tool.
 */
const built = new Map<string, Uint8Array>()
function zipTree(flags: readonly string[]): Uint8Array {
  const key = flags.join(' ')
  const hit = built.get(key)
  if (hit !== undefined) return hit

  const root = join(KEEP, `tree-${built.size}`)
  for (const f of TREE) {
    const path = join(root, f.name)
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, f.data)
  }

  const out = join(root, 'out.zip')
  // `-q` only; the status is the sensor. `spawnSync` rather than
  // `execFileSync` for the reason `zip.test.ts` records: `execFileSync`
  // *throws* on non-zero, so an `expect(status).toBe(0)` over it is never
  // reached and can never itself go red. A missing binary gives `null`, which
  // this comparison rejects — that is the no-guard decision failing closed.
  const res = spawnSync('/usr/bin/zip', [...flags, '-q', out, 'mimetype', 'ref'], { cwd: root })
  expect(res.status, `/usr/bin/zip ${key}: ${res.stderr?.toString() ?? ''}`).toBe(0)

  const bytes = new Uint8Array(readFileSync(out))
  built.set(key, bytes)
  return bytes
}

const DEFAULT_ARCHIVE = (): Uint8Array => zipTree(['-r'])
const NO_EXTRA_ARCHIVE = (): Uint8Array => zipTree(['-r', '-X'])

/**
 * The two streaming archives, memoised the same way and for the same reason.
 *
 * Four spawns in total, two of them negative controls. They are built lazily
 * and cached rather than in a `beforeAll`, so a run that selects only the
 * tree tests pays for none of them — and `zip` on this fixture is a few
 * milliseconds, measured below in the file's own runtime.
 *
 * Both go through `spawnSync` rather than a shell, which also removes the
 * question of what the shell did to the stream. `expect` on `status` in each,
 * for the fail-closed reason the no-`HAVE_ZIP` note above gives: `spawnSync`
 * returns `status === null` for a missing binary, so these turn red rather
 * than skipping.
 */
const streamed = new Map<string, Uint8Array>()

/**
 * `zip` reading its *entry* from stdin, which it answers with ZIP64 — `-h2`:
 * *"streaming stdin creates Zip64 archives by default"*.
 *
 * Not a seekability effect, which is worth stating because the sibling below
 * is: measured, `zip -q out.zip - < soup.txt` and `cat soup.txt | zip -q
 * out.zip -` produce byte-identical ZIP64 archives. `zip` reserves ZIP64
 * because it cannot know the entry's size before reading it, pipe or not.
 * Pass `['-fz-']` for the control, which is Info-ZIP's own off switch.
 */
function zipStdinArchive(flags: readonly string[]): Uint8Array {
  const key = `stdin ${flags.join(' ')}`
  const hit = streamed.get(key)
  if (hit !== undefined) return hit

  const out = join(KEEP, `stdin-${streamed.size}.zip`)
  const res = spawnSync('/usr/bin/zip', [...flags, '-q', out, '-'], { input: SOUP })
  expect(res.status, `/usr/bin/zip ${key}: ${res.stderr?.toString() ?? ''}`).toBe(0)

  const bytes = new Uint8Array(readFileSync(out))
  streamed.set(key, bytes)
  return bytes
}

/**
 * `zip` writing the *archive* to stdout, where seekability decides everything.
 *
 * `seekable: false` leaves stdout as `spawnSync`'s pipe and the archive comes
 * back in `res.stdout`; `true` points stdout at a real file descriptor. Same
 * argv, same input, and the difference is general-purpose bit 3 — that is the
 * measurement the docblock above records, performed here rather than quoted.
 */
function zipStdoutArchive(seekable: boolean): Uint8Array {
  const key = `stdout seekable=${seekable}`
  const hit = streamed.get(key)
  if (hit !== undefined) return hit

  const root = join(KEEP, `stream-${streamed.size}`)
  mkdirSync(root, { recursive: true })
  writeFileSync(join(root, 'soup.txt'), SOUP)

  let bytes: Uint8Array
  if (seekable) {
    const out = join(root, 'out.zip')
    const fd = openSync(out, 'w')
    try {
      const res = spawnSync('/usr/bin/zip', ['-q', '-X', '-', 'soup.txt'], {
        cwd: root,
        stdio: ['ignore', fd, 'pipe'],
      })
      expect(res.status, `/usr/bin/zip ${key}: ${res.stderr?.toString() ?? ''}`).toBe(0)
    } finally {
      closeSync(fd)
    }
    bytes = new Uint8Array(readFileSync(out))
  } else {
    const res = spawnSync('/usr/bin/zip', ['-q', '-X', '-', 'soup.txt'], { cwd: root })
    expect(res.status, `/usr/bin/zip ${key}: ${res.stderr?.toString() ?? ''}`).toBe(0)
    bytes = new Uint8Array(res.stdout)
  }

  streamed.set(key, bytes)
  return bytes
}

// ---------------------------------------------------------------------------
// A test-local structural peek, for asserting properties of the *fixture*
// that `readZip`'s API deliberately does not expose (header flags, extra-field
// lengths). It is not a second reader and must not become one: it reads the
// central directory's fixed-offset fields and nothing else.
// ---------------------------------------------------------------------------

interface Peek {
  readonly centralAt: number
  readonly localAt: number
  readonly nameBytes: Uint8Array
  readonly flags: number
  readonly centralExtraLen: number
  readonly localExtraLen: number
}

function eocdAt(archive: Uint8Array, v: DataView): number {
  for (let i = archive.length - 22; i >= 0; i--) if (v.getUint32(i, true) === 0x06054b50) return i
  throw new Error('fixture has no end-of-central-directory record')
}

function peek(archive: Uint8Array): Peek[] {
  const v = new DataView(archive.buffer, archive.byteOffset, archive.byteLength)
  const eocd = eocdAt(archive, v)
  const count = v.getUint16(eocd + 10, true)
  let p = v.getUint32(eocd + 16, true)
  const out: Peek[] = []
  for (let i = 0; i < count; i++) {
    const nameLen = v.getUint16(p + 28, true)
    const extraLen = v.getUint16(p + 30, true)
    const commentLen = v.getUint16(p + 32, true)
    const localAt = v.getUint32(p + 42, true)
    out.push({
      centralAt: p,
      localAt,
      nameBytes: archive.slice(p + 46, p + 46 + nameLen),
      flags: v.getUint16(p + 8, true),
      centralExtraLen: extraLen,
      localExtraLen: v.getUint16(localAt + 28, true),
    })
    p += 46 + nameLen + extraLen + commentLen
  }
  return out
}

/** The central record for one entry, by name. Throws rather than returning undefined. */
function recordFor(archive: Uint8Array, name: string): Peek {
  const wanted = te.encode(name)
  const hit = peek(archive).find(
    r => r.nameBytes.length === wanted.length && r.nameBytes.every((b, i) => b === wanted[i])
  )
  if (hit === undefined) throw new Error(`fixture has no entry named ${name}`)
  return hit
}

/**
 * Every offset at which a 4-byte little-endian signature appears.
 *
 * Deliberately a whole-buffer scan and not a structured lookup: the ZIP64
 * records this is used for are the ones the reader is refusing to parse, so
 * locating them by parsing them would be circular. A signature can occur by
 * chance inside deflate output, which is why the assertions below pin the
 * *position* (`eocd - 20` for the locator) rather than merely the count.
 */
function signatureOffsets(archive: Uint8Array, sig: number): number[] {
  const v = new DataView(archive.buffer, archive.byteOffset, archive.byteLength)
  const out: number[] = []
  for (let i = 0; i + 4 <= archive.length; i++) if (v.getUint32(i, true) === sig) out.push(i)
  return out
}

/** The extra-field ids carried in one entry's **local** header, in order. */
function localExtraIds(archive: Uint8Array, rec: Peek): number[] {
  const v = new DataView(archive.buffer, archive.byteOffset, archive.byteLength)
  const nameLen = v.getUint16(rec.localAt + 26, true)
  const start = rec.localAt + 30 + nameLen
  const ids: number[] = []
  for (let p = start; p + 4 <= start + rec.localExtraLen; p += 4 + v.getUint16(p + 2, true)) {
    ids.push(v.getUint16(p, true))
  }
  return ids
}

/** The sole entry of a single-entry archive, which the streaming fixtures are. */
function onlyRecord(archive: Uint8Array): Peek {
  const records = peek(archive)
  expect(records, 'the streaming fixtures are single-entry by construction').toHaveLength(1)
  return records[0] as Peek
}

/** A copy with `patch` applied, so the original fixture stays usable. */
function mutate(archive: Uint8Array, patch: (bytes: Uint8Array, v: DataView) => void): Uint8Array {
  const copy = archive.slice()
  patch(copy, new DataView(copy.buffer, copy.byteOffset, copy.byteLength))
  return copy
}

const byName = (a: { readonly files: readonly ZipEntry[] }): Map<string, Uint8Array> =>
  new Map(a.files.map(f => [f.name, f.data]))

// ---------------------------------------------------------------------------

describe('readZip', () => {
  // -- Criterion 2: the foreign archive, default flags -----------------------

  it('CRITERION 2 — reads every entry of a default `zip -r` archive, bytes exact', async () => {
    const archive = DEFAULT_ARCHIVE()

    // First, that the fixture is the one the criterion asks for. Without this
    // the test could pass against an archive with no extra fields and no
    // stored entry, and the criterion would be reported met on a fixture that
    // never exercised either branch.
    for (const r of peek(archive)) {
      expect(r.localExtraLen, 'default `zip -r` writes local extra fields').toBeGreaterThan(0)
      // 28 local vs 24 central, measured. The assertion is the *inequality*,
      // not the two numbers: it is the disagreement that breaks a reader, and
      // pinning the widths would pin Info-ZIP's choice of optional fields.
      expect(r.centralExtraLen).not.toBe(r.localExtraLen)
    }

    const read = await readZip(archive)
    const got = byName(read)

    expect([...got.keys()].sort()).toEqual(TREE.map(f => f.name).sort())
    for (const f of TREE) expect(got.get(f.name), f.name).toEqual(f.data)

    // One stored and one deflated, as the criterion requires. Which entries
    // zip chooses to store is zip's heuristic, so this asserts the *coverage*
    // rather than the assignment: if a future zip deflates everything, this
    // goes red and says the fixture stopped exercising method 0.
    expect(new Set(read.files.map(f => f.method))).toEqual(new Set(['store', 'deflate']))
  })

  // -- Criterion 3: the foreign archive, -X ----------------------------------

  it('CRITERION 3 — reads a `zip -r -X` archive, which carries no extra fields', async () => {
    // This test is **blind to the extra-field bugs by construction**, and
    // that is worth saying out loud rather than leaving for someone to
    // rediscover: both the "ignores `extraLen`" and the "uses the central
    // `extraLen`" mutations were planted and this test stayed green under
    // each, because `-X` leaves both lengths at 0 and the two wrong formulas
    // give the right answer. Only the default-archive test above can see
    // them. Deleting that one as redundant with this one would silently
    // delete criterion 2's entire point.
    const archive = NO_EXTRA_ARCHIVE()

    for (const r of peek(archive)) {
      expect(r.localExtraLen, '`-X` suppresses extra fields').toBe(0)
      expect(r.centralExtraLen).toBe(0)
    }

    const got = byName(await readZip(archive))
    expect([...got.keys()].sort()).toEqual(TREE.map(f => f.name).sort())
    for (const f of TREE) expect(got.get(f.name), f.name).toEqual(f.data)
  })

  // -- Criterion 4: directory entries ----------------------------------------

  it('CRITERION 4 — reports directory entries as directories, never as files', async () => {
    for (const archive of [DEFAULT_ARCHIVE(), NO_EXTRA_ARCHIVE()]) {
      const read = await readZip(archive)

      expect([...read.directories].sort()).toEqual([...TREE_DIRS].sort())
      // The failure this guards is a zero-byte "file" called `ref/` appearing
      // in the container's file list, where a `.stst` consumer would look for
      // it by name and get an empty mask.
      expect(read.files.map(f => f.name).filter(n => n.endsWith('/'))).toEqual([])
      expect(read.files).toHaveLength(TREE.length)
    }
  })

  it('CRITERION 4 — refuses a directory entry that carries data, rather than discarding it', async () => {
    // Dropping bytes silently is the one outcome a container reader must not
    // have: the name says directory, the record says 11 bytes, and whichever
    // the reader believes it is throwing away something it was given. The
    // central record is patched to claim a size the entry does not have, which
    // is also a size/CRC lie — the point is that the *directory* rule is what
    // reports it, so the message has to name the entry.
    const archive = DEFAULT_ARCHIVE()
    const dir = recordFor(archive, 'ref/')
    const broken = mutate(archive, (_b, v) => v.setUint32(dir.centralAt + 24, 11, true))

    await expect(readZip(broken)).rejects.toThrow(/ref\//)
  })

  // -- Criterion 5: a non-ASCII name written by /usr/bin/zip -----------------

  it('CRITERION 5 — reads a non-ASCII entry name written by /usr/bin/zip', async () => {
    for (const archive of [DEFAULT_ARCHIVE(), NO_EXTRA_ARCHIVE()]) {
      // Bit 11 is set on this entry and clear on the ASCII ones, so the
      // archive drives both decode paths. Asserted because "the reader got
      // the name right" is weak evidence if every name took the same branch.
      expect(recordFor(archive, UNICODE_NAME).flags & 0x800).toBe(0x800)
      expect(recordFor(archive, 'mimetype').flags & 0x800).toBe(0)

      const got = byName(await readZip(archive))
      expect(got.get(UNICODE_NAME)).toEqual(SOUP)
    }
  })

  // -- Criterion 6: fidelity, NOT the criterion-2 evidence -------------------

  it('FIDELITY (not criterion 2) — round-trips our own writer: names, methods and bytes', async () => {
    // Design §12's "round trip" row. It says nothing about foreign archives
    // and cannot discharge criterion 2 — a writer and a reader that share one
    // misreading of the spec agree perfectly. What it does discharge is that
    // nothing is lost between the two halves we do control.
    const entries: ZipEntry[] = [
      { name: 'mimetype', data: MIMETYPE, method: 'store' },
      { name: 'scene.json', data: te.encode(JSON.stringify({ stage: { w: 640, h: 360 } })), method: 'deflate' },
      { name: UNICODE_NAME, data: SOUP, method: 'deflate' },
      // An empty entry: deflate of zero bytes is a real stream with a real
      // (zero) CRC, and an off-by-one in the payload slice shows up here first.
      { name: 'empty.bin', data: new Uint8Array(0), method: 'deflate' },
    ]

    const read = await readZip(await writeZip(entries))

    expect(read.directories).toEqual([])
    // Order too, which the foreign tests cannot assert: `writeZip` emits the
    // caller's array order on purpose (`mimetype` first, as ODF and EPUB do),
    // while `zip -r`'s order is a directory traversal.
    expect(read.files.map(f => f.name)).toEqual(entries.map(e => e.name))
    expect(read.files.map(f => f.method)).toEqual(entries.map(e => e.method))
    for (const [i, e] of entries.entries()) expect((read.files[i] as ZipEntry).data, e.name).toEqual(e.data)
  })

  // -- Criterion 7: a CRC mismatch throws ------------------------------------

  it('CRITERION 7 — throws on a CRC mismatch, naming the entry', async () => {
    const archive = DEFAULT_ARCHIVE()

    // `mimetype` is stored, so its content sits in the archive verbatim and a
    // single flipped byte is a content change with no length change — every
    // offset in the file stays valid and the CRC is the only thing that can
    // report it. Located by searching for the content rather than by
    // recomputing the data offset, which would duplicate the very arithmetic
    // under test.
    let at = -1
    let found = 0
    outer: for (let i = 0; i + MIMETYPE.length <= archive.length; i++) {
      for (let j = 0; j < MIMETYPE.length; j++) if (archive[i + j] !== MIMETYPE[j]) continue outer
      at = i
      found++
    }
    // Exactly once: if the bytes appeared twice we would not know which copy
    // was patched, and if zero the patch below would be a no-op and this test
    // would be asserting a throw it had not caused.
    expect(found).toBe(1)

    const corrupt = mutate(archive, b => {
      b[at] = (b[at] as number) ^ 0x01
    })

    // The message has to let a caller act: which member of the container is
    // bad. "Invalid archive" would be true and useless.
    await expect(readZip(corrupt)).rejects.toThrow(/crc/i)
    await expect(readZip(corrupt)).rejects.toThrow(/mimetype/)

    // The control (§6.5a): the unpatched archive through the same call must
    // not throw. Without it, a reader that threw on everything would pass.
    await expect(readZip(archive)).resolves.toBeDefined()
  })

  // -- The central directory is authoritative --------------------------------

  it('treats the central directory as authoritative and refuses a local header that disagrees', async () => {
    // Trusting the local header is the classic zip-parsing vulnerability: the
    // two copies can disagree and an extractor that reads one while a scanner
    // reads the other can be made to disagree about what the archive contains.
    // Neither "believe the local" nor "ignore the disagreement" is acceptable
    // for a project file, so the reader reads the central record and *checks*
    // the local one against it.
    const archive = DEFAULT_ARCHIVE()
    const rec = recordFor(archive, 'mimetype')

    // The local copy of the name only: 'mimetype' -> 'zimetype'.
    const renamed = mutate(archive, b => {
      b[rec.localAt + 30] = 0x7a
    })
    await expect(readZip(renamed)).rejects.toThrow(/mimetype/)

    // And the local copy of the CRC only. A reader that validated against the
    // local CRC would now reject a perfectly good entry; one that ignored the
    // disagreement would be silently trusting whichever half it read first.
    const skewed = mutate(archive, (_b, v) => v.setUint32(rec.localAt + 14, 0xdeadbeef, true))
    await expect(readZip(skewed)).rejects.toThrow(/mimetype/)
  })

  // -- Loud refusals: the branches that must never guess ---------------------

  it('refuses an unsupported compression method by number, rather than returning plausible bytes', async () => {
    const archive = DEFAULT_ARCHIVE()
    const rec = recordFor(archive, 'ref/soup.txt')
    // 9 is deflate64 — a real method, close enough to deflate that an inflate
    // attempt may produce *some* output, which is precisely why guessing is
    // not an option here.
    const exotic = mutate(archive, (_b, v) => {
      v.setUint16(rec.centralAt + 10, 9, true)
      v.setUint16(rec.localAt + 8, 9, true)
    })
    await expect(readZip(exotic)).rejects.toThrow(/9/)
    await expect(readZip(exotic)).rejects.toThrow(/ref\/soup\.txt/)
  })

  it('refuses ZIP64 markers explicitly instead of mis-parsing them', async () => {
    // The sentinels, reached by patching a tree archive. This test used to
    // open by saying nothing here had ever produced a ZIP64 archive and that
    // `/usr/bin/zip` 3.0 could not emit one for these inputs; both are false
    // and the test below this one holds the specimen. What survives is the
    // reason for the refusal, which is unchanged: the 32-bit fields a ZIP64
    // archive leaves at 0xffffffff are sentinels, and a reader that takes
    // them at face value computes a 4 GiB offset into a 2 KiB file or wraps.
    //
    // A real archive cannot reach these four, because a `zip` that needed
    // the sentinels would need a 4 GiB member to put under them. They stay
    // synthetic on purpose; the three *structural* ZIP64 guards are driven by
    // the real article next door.
    const archive = DEFAULT_ARCHIVE()
    const v0 = new DataView(archive.buffer, archive.byteOffset, archive.byteLength)
    const eocd = eocdAt(archive, v0)

    const sentinelCdOffset = mutate(archive, (_b, v) => v.setUint32(eocd + 16, 0xffffffff, true))
    await expect(readZip(sentinelCdOffset)).rejects.toThrow(/zip64/i)

    const sentinelCount = mutate(archive, (_b, v) => v.setUint16(eocd + 10, 0xffff, true))
    await expect(readZip(sentinelCount)).rejects.toThrow(/zip64/i)

    // Three disjuncts guard the per-entry record — uncompressed size,
    // compressed size and local offset — and only the first was exercised,
    // measured by instrumenting the branch and running this file. One
    // satisfied disjunct cannot show the other two are wired, so all three
    // are patched, each on its own copy.
    const rec = recordFor(archive, 'ref/soup.txt')
    for (const [field, at] of [['uncompressed size', 24], ['compressed size', 20], ['local offset', 42]] as const) {
      const sentinel = mutate(archive, (_b, v) => v.setUint32(rec.centralAt + at, 0xffffffff, true))
      await expect(readZip(sentinel), field).rejects.toThrow(/zip64/i)
      await expect(readZip(sentinel), field).rejects.toThrow(/ref\/soup\.txt/)
    }

    // And the central-side `rejectZip64Extra` call, which the local-side one
    // in the real-specimen test does not cover: the default tree archive
    // carries real central extra fields, so relabelling the first field's id
    // as 0x0001 is a one-field edit to a record `zip` actually wrote.
    const withZip64Extra = mutate(archive, (_b, v) => {
      const nameLen = v.getUint16(rec.centralAt + 28, true)
      v.setUint16(rec.centralAt + 46 + nameLen, 0x0001, true)
    })
    expect(rec.centralExtraLen, 'the mutation needs a central extra field to relabel').toBeGreaterThan(4)
    await expect(readZip(withZip64Extra)).rejects.toThrow(/zip64 extra field/i)
  })

  // -- Criterion 2: ZIP64 and data descriptors, from the real producer -------

  it('CRITERION 2 — refuses a real ZIP64 archive from /usr/bin/zip, and reads the -fz- control', async () => {
    const archive = zipStdinArchive([])
    const v = new DataView(archive.buffer, archive.byteOffset, archive.byteLength)
    const eocd = eocdAt(archive, v)

    // The fixture, before the reader sees it. If `zip` ever stops emitting
    // ZIP64 here these three fail and say so — which is the sentence "the
    // fixture is no longer the archive this test needs", and is deliberately
    // not the same sentence as "the reader stopped refusing".
    expect(signatureOffsets(archive, 0x07064b50), 'ZIP64 locator, immediately before the EOCD')
      .toContain(eocd - 20)
    expect(signatureOffsets(archive, 0x06064b50).length, 'a ZIP64 end-of-central-directory record')
      .toBeGreaterThan(0)
    expect(localExtraIds(archive, onlyRecord(archive)), 'a 0x0001 ZIP64 extra field locally')
      .toContain(0x0001)

    await expect(readZip(archive)).rejects.toThrow(/zip64/i)
    await expect(readZip(archive)).rejects.toThrow(/locator/i)

    // The control, and it is doing two jobs. It shows the refusal is keyed to
    // ZIP64 rather than to "an archive whose entry came from stdin" — same
    // command, one extra flag — and it shows `readZip` can read this producer
    // at all, so the throw above is not the reader failing on the shape.
    const control = zipStdinArchive(['-fz-'])
    expect(signatureOffsets(control, 0x07064b50), '-fz- suppresses the locator').toEqual([])
    expect(signatureOffsets(control, 0x06064b50), '-fz- suppresses the ZIP64 EOCD').toEqual([])
    expect(localExtraIds(control, onlyRecord(control)), '-fz- suppresses the 0x0001 extra').not.toContain(0x0001)

    const read = await readZip(control)
    expect(read.files.map(f => f.data)).toEqual([SOUP])
  })

  it('reaches the two ZIP64 guards the locator throw shadows, on the same real archive', async () => {
    // The locator sits before every other ZIP64 check, so the specimen above
    // proves one guard and hides two. Each is reached by disabling exactly
    // the guard in front of it — on the real archive, so the bytes each one
    // reads are still Info-ZIP's and not this file's.
    const archive = zipStdinArchive([])
    const v0 = new DataView(archive.buffer, archive.byteOffset, archive.byteLength)
    const eocd = eocdAt(archive, v0)

    // Locator signature blanked. What catches the archive next is its own
    // `0x0001` local extra field, which `-X` does not even remove — asserted
    // present above, so this is the real field and not a planted one.
    const noLocator = mutate(archive, (_b, v) => v.setUint32(eocd - 20, 0x0a0b0c0d, true))
    await expect(readZip(noLocator)).rejects.toThrow(/zip64 extra field/i)

    // And with the central directory pointed at the ZIP64 end-of-central-
    // directory record this archive genuinely contains, at the offset it
    // genuinely sits at. `cdSize` moves with it so the bounds check passes
    // and the ZIP64 branch is what reports, rather than a truncation.
    const z64Eocd = signatureOffsets(archive, 0x06064b50)[0] as number
    const atZip64Eocd = mutate(noLocator, (_b, v) => {
      v.setUint32(eocd + 16, z64Eocd, true)
      v.setUint32(eocd + 12, eocd - 20 - z64Eocd, true)
    })
    await expect(readZip(atZip64Eocd)).rejects.toThrow(/points at a ZIP64 record/i)
  })

  it('refuses a data descriptor on flag bit 3 alone, nothing else changed', async () => {
    // Flag bit 3 moves the CRC and both sizes to a record *after* the data,
    // leaving the local header's copies zero. This comment used to go on to
    // say that `/usr/bin/zip` 3.0 does not emit one "even when writing to a
    // pipe (measured)", and that the refusal was therefore about an absence
    // of evidence. It emits one whenever its stdout is a pipe; the earlier
    // measurement used a shell redirect, which is seekable. The specimen is
    // in the next test and the mechanism is in this file's docblock.
    //
    // What the refusal is really about, now that the evidence exists: this
    // reader takes both sizes and the CRC from the central directory, so it
    // would very likely cope — and `likely` is not the standard for a user's
    // only copy of their project (plan §1.2k). Refusing a format we can now
    // produce and test is a decision, not a gap.
    //
    // The patched version stays because it is the *narrow* control: it is the
    // default tree archive with two flag words changed and nothing else, so
    // bit 3 alone is what the refusal keys on, which a real streamed archive
    // (different producer invocation, different entry, no extra fields)
    // cannot show on its own.
    const archive = DEFAULT_ARCHIVE()
    const rec = recordFor(archive, 'ref/soup.txt')
    const patched = mutate(archive, (_b, v) => {
      v.setUint16(rec.centralAt + 8, rec.flags | 0x08, true)
      v.setUint16(rec.localAt + 6, rec.flags | 0x08, true)
    })
    await expect(readZip(patched)).rejects.toThrow(/data descriptor/i)
    await expect(readZip(archive), 'the same archive without bit 3 reads').resolves.toBeDefined()
  })

  it('CRITERION 2 — refuses a real data-descriptor archive from /usr/bin/zip, and reads the seekable control', async () => {
    const piped = zipStdoutArchive(false)
    const redirected = zipStdoutArchive(true)

    // The fixture property, asserted before the reader runs and asserted on
    // both halves, because the pair *is* the evidence: identical argv and
    // identical input, and bit 3 differs. Either assertion failing means this
    // host's `zip` no longer patches a seekable header, which is a statement
    // about the host and not about `readZip`.
    expect(onlyRecord(piped).flags & 0x08, 'stdout a pipe: bit 3 set').toBe(0x08)
    expect(onlyRecord(redirected).flags & 0x08, 'stdout a file: bit 3 clear').toBe(0)

    await expect(readZip(piped)).rejects.toThrow(/data descriptor/i)
    // Naming the entry is the part a caller can act on, and `soup.txt` is the
    // real name Info-ZIP recorded rather than one this file chose.
    await expect(readZip(piped)).rejects.toThrow(/soup\.txt/)

    // The control reads, bytes exact. Without it the test would be satisfied
    // by a reader that refused everything this producer writes.
    const read = await readZip(redirected)
    expect(read.files.map(f => f.name)).toEqual(['soup.txt'])
    expect(read.files.map(f => f.data)).toEqual([SOUP])
  })

  it('refuses an encrypted entry by name instead of failing its CRC', async () => {
    // Bit 0 means the data is encrypted. Without this branch the entry would
    // still be rejected — the decrypted-looking bytes would fail the CRC — but
    // under a message that sends the caller looking for corruption.
    const archive = DEFAULT_ARCHIVE()
    const rec = recordFor(archive, 'mimetype')
    const locked = mutate(archive, (_b, v) => {
      v.setUint16(rec.centralAt + 8, rec.flags | 0x01, true)
      v.setUint16(rec.localAt + 6, rec.flags | 0x01, true)
    })
    await expect(readZip(locked)).rejects.toThrow(/encrypt/i)
  })

  it('refuses a truncated archive and an offset that leaves the file', async () => {
    const archive = DEFAULT_ARCHIVE()

    // Tail truncation takes the EOCD with it, which is the only record whose
    // absence a reader can detect without guessing.
    await expect(readZip(archive.slice(0, archive.length - 8))).rejects.toThrow()
    await expect(readZip(new Uint8Array(0))).rejects.toThrow()

    // A central record pointing past the end. The reader must not index off
    // the end of the buffer and call the undefined bytes an entry.
    const rec = recordFor(archive, 'mimetype')
    const adrift = mutate(archive, (_b, v) => v.setUint32(rec.centralAt + 42, archive.length + 4096, true))
    await expect(readZip(adrift)).rejects.toThrow()

    // A size that runs off the end from a valid start.
    const overlong = mutate(archive, (_b, v) => v.setUint32(rec.centralAt + 20, archive.length, true))
    await expect(readZip(overlong)).rejects.toThrow()
  })
})
